#method 2 combining csv all files using sqllite
import os
import pandas as pd
import sqlite3

# === CONFIG ===
folder_path = "nhanes_csv"   # folder with your CSVs
db_path = os.path.join(folder_path, "NHANES_lab.db")
final_csv = os.path.join(folder_path, "NHANES_lab_merged_all.csv")

# Collect all CSV files
csv_files = [f for f in os.listdir(folder_path) if f.endswith(".csv")]
csv_files.sort()
print(f"Processing {len(csv_files)} files...")

# Initialize SQLite database
if os.path.exists(db_path):
    os.remove(db_path)
conn = sqlite3.connect(db_path)

# Start with the first file
first_file = csv_files[0]
print(f"Initializing with {first_file} ...")
df = pd.read_csv(os.path.join(folder_path, first_file), engine="python", on_bad_lines="skip")
df.columns = df.columns.str.strip().str.upper()
df.to_sql("merged", conn, index=False, if_exists="replace")

# Merge the rest incrementally
for i, file in enumerate(csv_files[1:], start=2):
    print(f"[{i}/{len(csv_files)}] Merging {file} ...")

    try:
        df_new = pd.read_csv(os.path.join(folder_path, file), engine="python", on_bad_lines="skip")
    except Exception as e:
        print(f"Skipping {file}: {e}")
        continue

    df_new.columns = df_new.columns.str.strip().str.upper()
    if "SEQN" not in df_new.columns:
        continue

    # Add suffix to avoid duplicate column names
    suffix = os.path.splitext(file)[0]
    rename_map = {col: f"{col}_{suffix}" for col in df_new.columns if col != "SEQN"}
    df_new = df_new.rename(columns=rename_map)

    # Save new table
    table_name = f"t{i}"
    df_new.to_sql(table_name, conn, index=False, if_exists="replace")

    # Merge into master table (SQL JOIN)
    merge_query = f"""
        CREATE TABLE merged_new AS
        SELECT COALESCE(m.SEQN, t.SEQN) AS SEQN, *
        FROM merged m
        FULL OUTER JOIN {table_name} t
        ON m.SEQN = t.SEQN
    """
    # SQLite doesn’t support FULL OUTER JOIN natively → workaround:
    merge_query = f"""
        CREATE TABLE merged_new AS
        SELECT m.SEQN,
               m.*,
               t.*
        FROM merged m
        LEFT JOIN {table_name} t ON m.SEQN = t.SEQN
        UNION
        SELECT t.SEQN,
               m.*,
               t.*
        FROM {table_name} t
        LEFT JOIN merged m ON m.SEQN = t.SEQN
    """

    conn.execute("DROP TABLE IF EXISTS merged_new;")
    conn.execute(merge_query)
    conn.execute("DROP TABLE merged;")
    conn.execute("ALTER TABLE merged_new RENAME TO merged;")
    conn.commit()

# Export final merged dataset
print(f"Exporting to {final_csv} ...")
final_df = pd.read_sql("SELECT * FROM merged", conn)
final_df.to_csv(final_csv, index=False)
conn.close()
print("Done! Final file:", final_csv)

