import pyreadstat

# === CONFIG ===
input_folder = "/content/drive/MyDrive/NHANES_Data/nhanes_xpt"
output_csv = "/content/drive/MyDrive/NHANES_Data/NHANES_diabetes_merged_features.csv"

# === VARIABLE MAPPING ===
var_map = {
    "LBXGLU": ["LBXGLU", "GLU_F", "GLU"],
    "LBXIN": ["LBXIN", "INS"],
    "LBXGH": ["LBXGH", "GHB"],
    "LBXTC": ["LBXTC", "TCHOL"],
    "LBXTR": ["LBXTR", "TRIGLY"],
    "LBXSCR": ["LBXSCR", "CREAT"],
    "URXUAC": ["URXUAC", "URXCR"],
    "BP_SYS": ["BPXSY1", "BP_SYS"],
    "BP_DIA": ["BPXDI1", "BP_DIA"],
    "LBXHDL": ["LBXHDL"],
    "LBXLDL": ["LBXLDL"],
    "LBXEGFR": ["LBXEGFR"]
}

all_dfs = []

# === HELPER FUNCTIONS ===
def glucose_category(glu):
    if pd.isna(glu): return None
    if glu < 100: return "Normal"
    elif 100 <= glu < 126: return "Prediabetes"
    else: return "Diabetes"

def hba1c_category(hba1c):
    if pd.isna(hba1c): return None
    if hba1c < 5.7: return "Normal"
    elif 5.7 <= hba1c < 6.5: return "Prediabetes"
    else: return "Diabetes"

def bp_category(sys, dia):
    if pd.isna(sys) or pd.isna(dia): return None
    if sys < 120 and dia < 80: return "Normal"
    elif 120 <= sys < 130 and dia < 80: return "Elevated"
    elif 130 <= sys < 140 or 80 <= dia < 90: return "Hypertension Stage 1"
    else: return "Hypertension Stage 2"

def egfr_stage(egfr):
    if pd.isna(egfr): return None
    if egfr >= 90: return 1
    elif 60 <= egfr < 90: return 2
    elif 45 <= egfr < 60: return 3
    elif 30 <= egfr < 45: return 4
    else: return 5

# === READ AND PROCESS FILES ===
for file in sorted(os.listdir(input_folder)):
    if not file.lower().endswith(".xpt"):
        continue

    file_path = os.path.join(input_folder, file)
    try:
        df, meta = pyreadstat.read_xport(file_path, encoding="latin1")
    except Exception as e:
        print(f"Skipping {file}: {e}")
        continue

    df.columns = df.columns.str.strip()  # remove whitespace

    cols_to_keep = ["SEQN"]
    rename_dict = {}
    for target, options in var_map.items():
        for col in options:
            if col in df.columns:
                cols_to_keep.append(col)
                rename_dict[col] = target
                break

    if len(cols_to_keep) == 1:  # Only SEQN exists
        continue

    df = df[cols_to_keep].copy()
    df.rename(columns=rename_dict, inplace=True)
    df["SEQN"] = pd.to_numeric(df["SEQN"], errors="coerce")
    df.dropna(subset=["SEQN"], inplace=True)

    # Add survey cycle from filename (e.g., 'D' from 'GLU_D.xpt')
    cycle = file.split("_")[-1].split(".")[0]
    df["cycle"] = cycle

    all_dfs.append(df)
    print(f"Loaded {file}: columns={list(df.columns)} rows={df.shape[0]}")

# === VERTICAL CONCAT ===
if not all_dfs:
    print("No valid data found.")
else:
    merged = pd.concat(all_dfs, ignore_index=True)
    merged.drop_duplicates(subset=["SEQN"], inplace=True)

    # === DERIVED FEATURES ===
    if "LBXGLU" in merged.columns:
        merged["GLU_category"] = merged["LBXGLU"].apply(glucose_category)
    if "LBXGH" in merged.columns:
        merged["HBA1C_category"] = merged["LBXGH"].apply(hba1c_category)
    if "BP_SYS" in merged.columns and "BP_DIA" in merged.columns:
        merged["BP_category"] = merged.apply(lambda row: bp_category(row["BP_SYS"], row["BP_DIA"]), axis=1)
    if "LBXEGFR" in merged.columns:
        merged["EGFR_stage"] = merged["LBXEGFR"].apply(egfr_stage)

    # Flags for abnormal labs
    if "LBXTR" in merged.columns:
        merged["High_TG"] = merged["LBXTR"] > 150
    if "LBXTC" in merged.columns:
        merged["High_TC"] = merged["LBXTC"] > 200
    if "LBXLDL" in merged.columns:
        merged["High_LDL"] = merged["LBXLDL"] > 130
    if "LBXHDL" in merged.columns:
        merged["Low_HDL"] = merged["LBXHDL"] < 40

    # === SAVE OUTPUT ===
    merged.to_csv(output_csv, index=False)
    print(f"\nVertical merge with features complete → {output_csv}")
    print(f"Shape: {merged.shape}")

