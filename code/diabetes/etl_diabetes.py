import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler, LabelEncoder
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import classification_report, roc_auc_score
from imblearn.over_sampling import SMOTE

# === Load dataset ===
df = pd.read_csv("/content/drive/MyDrive/NHANES_Data/NHANES_diabetes_cleaned.csv")

# === Drop ID column and set target ===
target = "GLU_category"
X = df.drop(columns=["SEQN", target])
y = df[target]

# === Encode categorical columns ===
for col in X.columns:
    if X[col].dtype == "object":
        le = LabelEncoder()
        X[col] = le.fit_transform(X[col].astype(str))

# === Encode target as well (if string) ===
if y.dtype == "object":
    le_y = LabelEncoder()
    y = le_y.fit_transform(y)

# === Split data ===
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.3, random_state=42, stratify=y
)

# === Balance data with SMOTE ===
sm = SMOTE(random_state=42)
X_train_res, y_train_res = sm.fit_resample(X_train, y_train)

# === Scale ===
scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train_res)
X_test_scaled = scaler.transform(X_test)

# === Train model ===
model = LogisticRegression(max_iter=1000, penalty='l2', C=0.5)
model.fit(X_train_scaled, y_train_res)

# === Evaluate ===
y_pred = model.predict(X_test_scaled)
y_pred_proba = model.predict_proba(X_test_scaled)

print("Model training complete.\n")
print(classification_report(y_test, y_pred))
print("ROC-AUC (ovr, probabilities):", roc_auc_score(y_test, y_pred_proba, multi_class='ovr'))

