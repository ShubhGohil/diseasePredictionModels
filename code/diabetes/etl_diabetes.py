#2 Horizonal merging(multiple columns for diffrent year cycle)
import os
import pandas as pd
import pyreadstat

# === CONFIG ===
folder = "/content/drive/MyDrive/NHANES_Data/nhanes_xpt"
output_path = "/content/drive/MyDrive/NHANES_Data/merged_diabetes_dataset.csv"

# === VARIABLES OF INTEREST ===
target_vars = {
    "GLU": ["LBXGLU"],
    "INS": ["LBXIN"],
    "TCHOL": ["LBXTC"],
    "TRIGLY": ["LBXTR"],
    "GHB": ["LBXGH"],
    "BIOPRO": ["LBXSCR", "LBXURIC"],
}

merged_df = None

# === MAIN MERGE LOOP ===
for file in os.listdir(folder):
    fname = file.upper()
    for prefix, cols in target_vars.items():
        if fname.startswith(prefix) and fname.endswith(".XPT"):
            file_path = os.path.join(folder, file)
            try:
                df, meta = pyreadstat.read_xport(file_path)
            except Exception as e:
                print(f"Error reading {file}: {e}")
                continue

            if "SEQN" not in df.columns:
                print(f"Skipping {file}: missing SEQN")
                continue

            # Keep only relevant columns
            keep_cols = ["SEQN"] + [c for c in cols if c in df.columns]
            df = df[keep_cols]

            # Add suffix for cycle (E/F/G etc.)
            cycle = fname.split("_")[-1].split(".")[0]
            df = df.add_suffix(f"_{cycle}")
            df.rename(columns={f"SEQN_{cycle}": "SEQN"}, inplace=True)

            # Merge horizontally on SEQN
            if merged_df is None:
                merged_df = df
            else:
                merged_df = pd.merge(merged_df, df, on="SEQN", how="outer")

            print(f"Merged {file} → shape now {merged_df.shape}")

# === SAVE OUTPUT ===
if merged_df is not None:
    merged_df.to_csv(output_path, index=False)
    print("\nMerge complete!")
    print(f"Rows: {len(merged_df)}, Cols: {len(merged_df.columns)}")
    print(f"Saved merged dataset → {output_path}")
else:
    print("No valid files found.")

