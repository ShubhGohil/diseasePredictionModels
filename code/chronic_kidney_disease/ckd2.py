# Cross-Validation Techniques

# ## K-Fold Cross-Validation
# K-Fold Cross-Validation is a widely used technique to evaluate the performance of a machine learning model on unseen data. It helps in getting a more reliable estimate of model performance compared to a single train-test split, especially with limited data.
# - **How it works:** The dataset is divided into k equal-sized folds. The model is trained on k-1 folds and evaluated on the remaining fold. This process is repeated k times, with each fold serving as the test set exactly once. The final performance metric is the average of the scores obtained in each fold.
# - **Potential benefits:** Provides a more robust estimate of model performance, reduces the variance of the performance estimate compared to a single split, makes better use of the available data.
# - **Potential drawbacks:** Can be computationally expensive for large datasets or complex models.

# ## Stratified K-Fold Cross-Validation
# Stratified K-Fold Cross-Validation is a variation of k-fold cross-validation where each fold contains approximately the same proportion of samples of each target class as the complete set. This is particularly useful for imbalanced datasets to ensure that each fold is representative of the overall data distribution.
# - **How it works:** Similar to k-fold, but the splitting is done in a way that maintains the original class distribution in each fold.
# - **Potential benefits:** Ensures that each fold is representative, important for classification tasks with imbalanced classes.

# ## Leave-One-Out Cross-Validation (LOOCV)
# Leave-One-Out Cross-Validation is an extreme case of k-fold cross-validation where k is equal to the number of data instances. In each iteration, a single data instance is used as the test set, and the remaining instances are used as the training set.
# - **How it works:** The model is trained on n-1 instances and tested on the single remaining instance, repeated n times.
# - **Potential benefits:** Makes maximum use of the data for training, provides a nearly unbiased estimate of the model's performance.
# - **Potential drawbacks:** Very computationally expensive for large datasets.

