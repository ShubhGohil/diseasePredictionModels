# Feature Selection Methods

## Correlation Analysis
# Correlation analysis measures the linear relationship between features and the target variable. Features with high absolute correlation with the target are often considered more relevant.
# - **How it works:** Calculates the correlation coefficient (e.g., Pearson, Spearman) between each feature and the target variable.
# - **Potential benefits:** Simple to understand and implement, can identify redundant features.

# ## Mutual Information
# Mutual information measures the dependency between two variables. It quantifies how much information one variable provides about another. For feature selection, it measures the dependency between each feature and the target variable.
# - **How it works:** Based on entropy, it calculates the reduction in uncertainty about the target variable when the value of a feature is known.
# - **Potential benefits:** Can capture non-linear relationships, effective for both numerical and categorical features.

# ## Feature Importance from Tree-Based Models
# Tree-based models like Random Forests and Gradient Boosting can provide a score indicating the importance of each feature in the model's predictions.
# - **How it works:** Importance is typically calculated based on how much each feature contributes to reducing impurity (e.g., Gini impurity, entropy) across all trees in the ensemble.
# - **Potential benefits:** Captures interactions between features, relatively easy to interpret.

# ## Recursive Feature Elimination (RFE)
# RFE is a wrapper method that recursively removes features and builds a model on the remaining features. The performance of the model is used to rank the features.
# - **How it works:** Starts with all features, trains a model, removes the least important feature, and repeats until the desired number of features is reached.
# - **Potential benefits:** Can find optimal subsets of features, considers feature interactions.

